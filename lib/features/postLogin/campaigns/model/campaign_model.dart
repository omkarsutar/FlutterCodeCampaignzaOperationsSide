import '../../../../core/services/entity_service.dart';

class ModelCampaignFields {
  static const String table = 'campaign';
  static const String tableViewWithForeignKeyLabels = 'view_campaigns';

  static const String poId = 'po_id';
  static const String poTotalAmount = 'po_total_amount';
  static const String poLineItemCount = 'po_line_item_count';
  static const String poRouteId = 'po_route_id';
  static const String poShopId = 'po_shop_id';
  static const String userComment = 'user_comment';
  static const String adminComment = 'admin_comment';
  static const String profitToShop = 'profit_to_shop';
  static const String poLat = 'po_lat';
  static const String poLong = 'po_long';
  static const String status = 'status';
  static const String createdBy = 'created_by';
  static const String updatedBy = 'updated_by';
  static const String createdAt = 'created_at';
  static const String visitOrder = 'visit_order';
  static const String updatedAt = 'updated_at';

  static const Map<String, String> labels = {
    poId: 'PO',
    poTotalAmount: 'Total Amount',
    poLineItemCount: 'Line Item Count',
    poRouteId: 'Route',
    poShopId: 'Shop',
    userComment: 'User Comment',
    adminComment: 'Admin Comment',
    profitToShop: 'Profit to Shop',
    poLat: 'Latitude',
    poLong: 'Longitude',
    status: 'Status',
    createdBy: 'Created By',
    updatedBy: 'Updated By',
    createdAt: 'Created At',
    updatedAt: 'Updated At',
    visitOrder: 'Visit Order',
  };

  static String getLabel(String field) => labels[field] ?? field;
}

class ModelCampaign {
  final String? poId; // nullable, generated by DB
  final double? poTotalAmount; // nullable
  final int? poLineItemCount; // nullable
  final String? poRouteId; // required FK
  final String? poShopId; // required FK
  final String? userComment; // nullable
  final String? adminComment; // nullable
  final double? profitToShop; // nullable
  final double? poLat; // nullable
  final double? poLong; // nullable
  final String? status; // nullable, DB default
  final String? createdBy; // required FK
  final String? updatedBy; // required FK
  final DateTime? createdAt; // nullable, DB default
  final DateTime? updatedAt; // nullable, DB default
  final int? visitOrder; // nullable, from view join
  final Map<String, dynamic> _resolvedLabels;

  ModelCampaign({
    this.poId,
    this.poTotalAmount,
    this.poLineItemCount,
    this.poRouteId,
    this.poShopId,
    this.userComment,
    this.adminComment,
    this.profitToShop,
    this.poLat,
    this.poLong,
    this.status,
    this.createdBy,
    this.updatedBy,
    this.createdAt,
    this.updatedAt,
    this.visitOrder,
    Map<String, dynamic>? resolvedLabels,
  }) : _resolvedLabels = resolvedLabels ?? const {};

  Map<String, dynamic> get resolvedLabels => _resolvedLabels;

  factory ModelCampaign.fromMap(Map<String, dynamic> map) {
    final labelEntries = <String, dynamic>{};
    for (final entry in map.entries) {
      if (entry.key.endsWith('_label')) {
        labelEntries[entry.key] = entry.value;
      }
    }

    return ModelCampaign(
      poId: map[ModelCampaignFields.poId] as String?,
      poTotalAmount: map[ModelCampaignFields.poTotalAmount] != null
          ? double.tryParse(map[ModelCampaignFields.poTotalAmount].toString())
          : null,
      poLineItemCount: map[ModelCampaignFields.poLineItemCount] != null
          ? int.tryParse(map[ModelCampaignFields.poLineItemCount].toString())
          : null,
      poRouteId: map[ModelCampaignFields.poRouteId] as String?,
      poShopId: map[ModelCampaignFields.poShopId] as String?,
      userComment: map[ModelCampaignFields.userComment] as String?,
      adminComment: map[ModelCampaignFields.adminComment] as String?,
      profitToShop: map[ModelCampaignFields.profitToShop] != null
          ? double.tryParse(map[ModelCampaignFields.profitToShop].toString())
          : null,
      poLat: map[ModelCampaignFields.poLat] != null
          ? double.tryParse(map[ModelCampaignFields.poLat].toString())
          : null,
      poLong: map[ModelCampaignFields.poLong] != null
          ? double.tryParse(map[ModelCampaignFields.poLong].toString())
          : null,
      status: map[ModelCampaignFields.status] as String?,
      createdBy: map[ModelCampaignFields.createdBy] as String?,
      updatedBy: map[ModelCampaignFields.updatedBy] as String?,
      createdAt: map[ModelCampaignFields.createdAt] != null
          ? DateTime.tryParse(map[ModelCampaignFields.createdAt].toString())
          : null,
      updatedAt: map[ModelCampaignFields.updatedAt] != null
          ? DateTime.tryParse(map[ModelCampaignFields.updatedAt].toString())
          : null,
      visitOrder: map[ModelCampaignFields.visitOrder] != null
          ? int.tryParse(map[ModelCampaignFields.visitOrder].toString())
          : null,
      resolvedLabels: labelEntries,
    );
  }

  Map<String, dynamic> toMap() {
    final map = <String, dynamic>{};

    if (poId != null) map[ModelCampaignFields.poId] = poId;
    if (poTotalAmount != null) {
      map[ModelCampaignFields.poTotalAmount] = poTotalAmount;
    }
    if (poLineItemCount != null) {
      map[ModelCampaignFields.poLineItemCount] = poLineItemCount;
    }
    if (poRouteId != null) {
      map[ModelCampaignFields.poRouteId] = poRouteId;
    }
    if (poShopId != null) {
      map[ModelCampaignFields.poShopId] = poShopId;
    }
    if (userComment != null) {
      map[ModelCampaignFields.userComment] = userComment;
    }
    if (adminComment != null) {
      map[ModelCampaignFields.adminComment] = adminComment;
    }
    if (profitToShop != null) {
      map[ModelCampaignFields.profitToShop] = profitToShop;
    }
    if (poLat != null) {
      map[ModelCampaignFields.poLat] = poLat;
    }
    if (poLong != null) {
      map[ModelCampaignFields.poLong] = poLong;
    }
    if (status != null) map[ModelCampaignFields.status] = status;
    if (createdBy != null) map[ModelCampaignFields.createdBy] = createdBy;
    if (updatedBy != null) map[ModelCampaignFields.updatedBy] = updatedBy;
    if (createdAt != null) {
      map[ModelCampaignFields.createdAt] = createdAt!.toIso8601String();
    }
    if (updatedAt != null) {
      map[ModelCampaignFields.updatedAt] = updatedAt!.toIso8601String();
    }
    if (visitOrder != null) {
      map[ModelCampaignFields.visitOrder] = visitOrder;
    }

    return map;
  }

  Map<String, dynamic> toJson() {
    return {
      'poId': poId,
      'poTotalAmount': poTotalAmount,
      'poLineItemCount': poLineItemCount,
      'poRouteId': poRouteId,
      'poShopId': poShopId,
      'userComment': userComment,
      'adminComment': adminComment,
      'profitToShop': profitToShop,
      'poLat': poLat,
      'poLong': poLong,
      'status': status,
      'createdBy': createdBy,
      'updatedBy': updatedBy,
      'createdAt': createdAt?.toIso8601String(),
      'updatedAt': updatedAt?.toIso8601String(),
      'visitOrder': visitOrder,
    };
  }

  factory ModelCampaign.fromJson(Map<String, dynamic> json) {
    return ModelCampaign(
      poId: json['poId'] as String,
      poTotalAmount: (json['poTotalAmount'] as num?)?.toDouble(),
      poLineItemCount: json['poLineItemCount'] as int?,
      poRouteId: json['poRouteId'] as String,
      poShopId: json['poShopId'] as String,
      userComment: json['userComment'] as String?,
      adminComment: json['adminComment'] as String?,
      profitToShop: (json['profitToShop'] as num?)?.toDouble(),
      poLat: (json['poLat'] as num?)?.toDouble(),
      poLong: (json['poLong'] as num?)?.toDouble(),
      status: json['status'] as String? ?? 'confirmed',
      createdBy: json['createdBy'] as String,
      updatedBy: json['updatedBy'] as String,
      createdAt: DateTime.tryParse(json['createdAt'] ?? '') ?? DateTime.now(),
      updatedAt: DateTime.tryParse(json['updatedAt'] ?? '') ?? DateTime.now(),
      visitOrder: json['visitOrder'] as int?,
    );
  }
}

class ModelCampaignMapper implements EntityMapper<ModelCampaign> {
  @override
  ModelCampaign fromMap(Map<String, dynamic> map) => ModelCampaign.fromMap(map);

  @override
  Map<String, dynamic> toMap(ModelCampaign entity) => entity.toMap();
}
